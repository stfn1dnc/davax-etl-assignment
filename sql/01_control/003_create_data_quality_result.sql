CREATE TABLE etl_control.data_quality_result (
    quality_result_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    run_id NUMBER,
    rule_name VARCHAR2(150) NOT NULL,
    table_name VARCHAR2(128) NOT NULL,
    column_name VARCHAR2(128),
    result_status VARCHAR2(20) NOT NULL,
    checked_rows NUMBER DEFAULT 0 NOT NULL,
    failed_rows NUMBER DEFAULT 0 NOT NULL,
    details VARCHAR2(4000),
    checked_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_data_quality_result
        PRIMARY KEY (quality_result_id),

    CONSTRAINT fk_data_quality_result_run
        FOREIGN KEY (run_id)
        REFERENCES etl_control.etl_run(run_id),

    CONSTRAINT ck_data_quality_status
        CHECK (result_status IN ('PASSED', 'FAILED', 'WARNING'))
);